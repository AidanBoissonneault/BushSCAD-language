/** Reads every upstream license or notice file that belongs to a shipped npm package. */
async function packageSection(packageRoot: string): Promise<string> {
  const manifest = JSON.parse(
    await readFile(join(packageRoot, 'package.json'), 'utf8'),
  ) as { name: string; version: string; license?: string };
  const noticeNames = (await readdir(packageRoot))
    .filter((name) =>
      /^(licen[sc]e|copying|notice)([-.]|$)|^third.?party.*notice/i.test(name),
    )
    .sort();
  const notices = await Promise.all(
    noticeNames.map((name) => readFile(join(packageRoot, name), 'utf8')),
  );
  if (notices.length === 0 && manifest.name === 'type-fest') {
    notices.push(typeFestNotice);
  }
  if (notices.length === 0) {
    throw new Error(
      `No license text found for shipped package ${manifest.name}`,
    );
  }
  return [
    `================================================================================\n${manifest.name} ${manifest.version}`,
    `Declared license: ${manifest.license ?? 'not specified'}`,
    ...notices.map((notice) => notice.trim()),
  ].join('\n\n');
}

/** Resolves an installed package from the project that owns its dependency. */
async function installedPackageRoot(
  packageRequire: ReturnType<typeof createRequire>,
  packageName: string,
): Promise<string> {
  let candidate = dirname(packageRequire.resolve(packageName));
  while (candidate !== dirname(candidate)) {
    try {
      const manifest = JSON.parse(
        await readFile(join(candidate, 'package.json'), 'utf8'),
      ) as { name?: string };
      if (manifest.name === packageName) return candidate;
    } catch {
      // Keep walking until the package that owns the resolved file is found.
    }
    candidate = dirname(candidate);
  }
  throw new Error(`Could not locate installed package ${packageName}`);
}

/** Writes the public language workspace's third-party license snapshot. */
async function generateLicenses(): Promise<void> {
  const packageRequire = createRequire(resolve(repositoryRoot, 'package.json'));
  const publicPackageNames = [...new Set(publicPackages)].sort();
  const packageSections = await Promise.all(
    publicPackageNames.map((packageName) =>
      installedPackageRoot(packageRequire, packageName).then(packageSection),
    ),
  );
  const notoLicense = await readFile(
    resolve(
      repositoryRoot,
      'packages/compiler/assets/fonts/NotoSans-LICENSE.txt',
    ),
    'utf8',
  );
  const occtException = await readFile(
    resolve(repositoryRoot, 'OCCT_LGPL_EXCEPTION.txt'),
    'utf8',
  );
  const occtSource = await readFile(
    resolve(repositoryRoot, 'OCCT-SOURCE.md'),
    'utf8',
  );

  const contents = [
    `BUSHSCAD THIRD-PARTY LICENSES AND NOTICES

Generated by scripts/licensing/generate-licenses.ts from the locked release dependencies.
BushSCAD itself is licensed under Apache-2.0; see the root LICENSE file.

This file covers third-party software and assets bundled in the public BushSCAD
language packages. It must accompany release artifacts.`,
    `OPEN CASCADE TECHNOLOGY NOTICE AND EXCEPTION

BushSCAD makes use of facilities provided by Open CASCADE Technology software.`,
    occtException.trim(),
    '',
    'OPEN CASCADE SOURCE CORRESPONDENCE',
    occtSource
      .replace(
        'see `THIRD-PARTY-NOTICES.txt` for the complete notices and exception text.',
        'the complete notices and exception text are included in this LICENSES file.',
      )
      .trim(),
    'NOTO SANS, NOTO SANS MONO, AND NOTO SERIF',
    notoLicense.trim(),
    'NPM COMPONENTS',
    ...packageSections,
  ].join('\n\n');
  await writeFile(resolve(repositoryRoot, 'LICENSES'), `${contents}\n`, 'utf8');
}

void generateLicenses().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
