import type { LanguageHelpEntry } from './types.js';

/** Keeps wrap intent examples comparable by using one outline with an inward dent. */
function wrapExample(intent: string): string {
  return `sketch outline = wrap([(-20, -10), (20, -10), (20, 10), (0, 4), (-20, 10)], ${intent});`;
}

/** Shows each supported direction word in a complete radius-arc sketch. */
function arcDirectionExample(direction: string): string {
  return `sketch cap = path(base = line((0, 0), (20, 0)), rim = arc((0, 0), 10, ${direction}));`;
}

