import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import type { SuiteCaseResult, SuiteRunResult } from './suiteTypes.js';

/** Writes the standalone visual suite report used for HTML and PDF review. */
export async function writeSuiteReportHtml(
  path: string,
  result: SuiteRunResult,
): Promise<void> {
  const cards = await Promise.all(result.cases.map(caseCard));
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, reportDocument(result, cards.join('\n')), 'utf8');
}

/**
 * Handles case card in the suite flow.
 */
async function caseCard(result: SuiteCaseResult): Promise<string> {
  const images = await Promise.all(
    result.screenshots.map(async (path) => ({
      name: viewName(path),
      data: `data:image/png;base64,${(await readFile(path)).toString('base64')}`,
    })),
  );
  const hero = images.find((image) => image.name === 'iso') ?? images[0];
  return `<article class="case ${result.status}">
  <div class="case-heading"><div><span class="status">${result.status.toUpperCase()}</span><h2>${escapeHtml(result.title)}</h2><code>${escapeHtml(result.id)}</code></div><div class="elapsed">${result.elapsedMs} ms</div></div>
  <p>${escapeHtml(result.description)}</p>
  <div class="case-grid">
    <div>${hero ? `<img class="hero" src="${hero.data}" alt="Isometric render of ${escapeHtml(result.title)}">` : '<div class="no-image">No render produced</div>'}</div>
    <div>
      <h3>Checks</h3>${checkList(result)}
      <h3>Capabilities</h3><div class="chips">${result.capabilities.map(chip).join('')}</div>
      ${diagnostics(result)}
    </div>
  </div>
  ${metricTable(result)}
  <details><summary>All rendered views and source</summary><div class="views">${images.map((image) => `<figure><img src="${image.data}" alt="${image.name} view"><figcaption>${image.name}</figcaption></figure>`).join('')}</div><pre>${escapeHtml(result.source)}</pre></details>
</article>`;
}

/**
 * Handles report document in the suite flow.
 */
function reportDocument(result: SuiteRunResult, cards: string): string {
  const passed = result.cases.filter(
    (entry) => entry.status === 'passed',
  ).length;
  return `<!doctype html><html><head><meta charset="utf-8"><title>${escapeHtml(result.title)}</title><style>${styles()}</style></head><body>
<header><div><p class="eyebrow">BushSCAD language true check</p><h1>${escapeHtml(result.title)}</h1><p>${escapeHtml(result.description)}</p></div><div class="score ${result.ok ? 'passed' : 'failed'}"><strong>${passed}/${result.cases.length}</strong><span>models passed</span></div></header>
<main>
<section class="summary"><div><h2>Run summary</h2><p>Started ${escapeHtml(result.startedAt)} - ${result.elapsedMs} ms</p><p>${result.coverage.covered.length}/${result.coverage.required.length} capabilities covered</p></div><div><h3>Manifest</h3>${checks(result.manifestChecks)}</div></section>
${result.coverage.missing.length > 0 ? `<section class="coverage-error"><strong>Missing capabilities:</strong> ${escapeHtml(result.coverage.missing.join(', '))}</section>` : ''}
${result.coverage.unknown.length > 0 ? `<section class="coverage-error"><strong>Unknown capabilities:</strong> ${escapeHtml(result.coverage.unknown.join(', '))}</section>` : ''}
${cards}</main><footer>Generated by @bushscad/model-analysis - ${escapeHtml(result.suiteRoot)}</footer></body></html>`;
}

/**
 * Handles check list in the suite flow.
 */
function checkList(result: SuiteCaseResult): string {
  return checks(result.checks);
}

/**
 * Handles checks in the suite flow.
 */
function checks(
  values: { passed: boolean; name: string; detail: string }[],
): string {
  return `<ul class="checks">${values.map((value) => `<li class="${value.passed ? 'pass' : 'fail'}"><strong>${value.passed ? '&#10003;' : '&#10005;'} ${escapeHtml(value.name)}</strong><span>${escapeHtml(value.detail)}</span></li>`).join('')}</ul>`;
}

/**
 * Handles diagnostics in the suite flow.
 */
function diagnostics(result: SuiteCaseResult): string {
  const messages = [
    ...result.errors.map((error) => error.message),
    ...result.validations
      .filter((value) => !value.passed)
      .map((value) => value.message),
    ...result.warnings,
  ];
  return messages.length > 0
    ? `<h3>Diagnostics</h3><ul class="diagnostics">${messages.map((message) => `<li>${escapeHtml(message)}</li>`).join('')}</ul>`
    : '';
}

/**
 * Handles metric table in the suite flow.
 */
function metricTable(result: SuiteCaseResult): string {
  if (result.meshes.length === 0) return '';
  return `<table><thead><tr><th>Mesh</th><th>Triangles</th><th>Dimensions (mm)</th><th>Volume (mm^3)</th><th>Topology</th></tr></thead><tbody>${result.meshes.map((mesh) => `<tr><td>${escapeHtml(mesh.key)}</td><td>${mesh.triangleCount}</td><td>${mesh.dimensions.map((value) => value.toFixed(2)).join(' x ')}</td><td>${Math.abs(mesh.signedVolume).toFixed(2)}</td><td>${escapeHtml(JSON.stringify(mesh.issues))}</td></tr>`).join('')}</tbody></table>`;
}

/**
 * Handles chip in the suite flow.
 */
function chip(value: string): string {
  return `<span>${escapeHtml(value)}</span>`;
}

/**
 * Handles view name in the suite flow.
 */
function viewName(path: string): string {
  return (
    path
      .replace(/\\/g, '/')
      .split('/')
      .pop()
      ?.replace(/\.png$/, '') ?? 'view'
  );
}

/**
 * Handles escape html in the suite flow.
 */
function escapeHtml(value: string): string {
  return value.replace(
    /[&<>"']/g,
    (char) =>
      ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[
        char
      ]!,
  );
}

