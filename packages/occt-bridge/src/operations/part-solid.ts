import type { MaterialAppearance, SourceSpan } from '@bushscad/ir';
import type { FaceFrame } from '../topology/face-labels.js';
import { boundsOverlap, readBounds } from '../core/geometry-utils.js';
import type { Bounds } from '../core/geometry-utils.js';
import type { GroupBuildState, OC } from '../bridge/bridge-types.js';
import type { SourceAttachmentPlane } from '../topology/source-edge-recovery.js';

/**
 * Defines the `PartSolidFuse` callback contract used by the operations layer.
 */
type PartSolidFuse = (
  a: OC,
  b: OC,
  span: SourceSpan,
  failureMessage?: string,
) => OC;

/**
 * Defines the `PartSolidRegister` callback contract used by the operations layer.
 */
type PartSolidRegister = (state: GroupBuildState, shape: OC) => void;

/**
 * Defines the `PartSolidRegisterAlias` callback contract used by the operations layer.
 */
type PartSolidRegisterAlias = (
  state: GroupBuildState,
  alias: string,
  shape: OC,
) => void;

/**
 * Adds an additive component to an explicit part without immediately fusing it.
 * Radial and grid loops often create many small bodies before details are
 * applied. Keeping them separate avoids repeatedly cutting and fusing an
 * increasingly complex part solid while face labels still resolve per source.
 */
export function addDeferredPartComponent(
  state: GroupBuildState,
  name: string,
  shape: OC,
  frame: FaceFrame,
  material: MaterialAppearance | null,
  attachmentPlane?: SourceAttachmentPlane,
): void {
  const owner = state.partSolidOwner;
  if (!owner) return;

  state.partSolidAliases.add(owner);
  state.partSolidAliases.add(name);
  state.partSolidComponents.set(name, shape);
  state.partSolidAliasComponents.set(name, name);
  if (!state.partSolidAliasComponents.has(owner)) {
    state.partSolidAliasComponents.set(owner, name);
  }
  if (!state.partSolidAliasShapes.has(name)) {
    state.partSolidAliasShapes.set(name, shape);
  }
  if (!state.partSolidAliasShapes.has(owner)) {
    state.partSolidAliasShapes.set(owner, shape);
  }
  if (attachmentPlane) {
    state.bodyAttachmentPlanes.set(name, attachmentPlane);
    state.partSolidAliasAttachmentPlanes.set(name, attachmentPlane);
  }

  state.bodyOwners.set(owner, owner);
  state.bodyOwners.set(name, owner);
  state.bodyEdgeModes.set(owner, 'outer');
  state.bodyEdgeModes.set(name, 'outer');
  state.bodyFrames.set(owner, state.bodyFrames.get(owner) ?? frame);
  state.bodyFrames.set(name, frame);
  state.bodyMaterials.set(owner, state.bodyMaterials.get(owner) ?? material);
  state.bodyMaterials.set(name, material);
  state.bodyShapes.set(owner, shape);
}

/**
 * Creates a cut feature alias without inheriting the target's source region.
 * A selector such as `pocket.top.edges` means the rim generated by the cut,
 * not the parent body's original top perimeter. The alias therefore points to
 * the cut result as its own inner-edge region.
 */
export function aliasDeferredPartCut(
  state: GroupBuildState,
  alias: string,
  target: string,
  cutRegionShape: OC,
  attachmentPlane?: SourceAttachmentPlane,
): void {
  const owner = state.partSolidOwner;
  if (!owner) return;
  const component = state.partSolidAliasComponents.get(target) ?? target;
  state.partSolidAliases.add(alias);
  state.partSolidAliasComponents.set(alias, component);
  state.partSolidAliasShapes.set(alias, cutRegionShape);
  if (attachmentPlane) {
    state.partSolidAliasAttachmentPlanes.set(alias, attachmentPlane);
  }
  state.bodyOwners.set(alias, owner);
  state.bodyEdgeModes.set(alias, 'inner');
}

/**
 * Cuts every deferred component whose bounds overlap the cutter.
 * A through-cut in a fused part should remove all intersecting material, but
 * applying it to each simple component is much cheaper than cutting an
 * already-fused aggregate on every loop iteration.
 */
export function cutDeferredPartComponents(options: {
  oc: OC;
  state: GroupBuildState;
  targetAlias: string;
  tool: OC;
  targetResult: OC;
  span: SourceSpan;
  applyCut: (shape: OC, tool: OC, span: SourceSpan) => OC;
  registerAlias: PartSolidRegisterAlias;
}): void {
  const {
    oc,
    state,
    targetAlias,
    tool,
    targetResult,
    span,
    applyCut,
    registerAlias,
  } = options;
  const owner = state.partSolidOwner;
  if (!owner) return;
  const targetComponent = state.partSolidAliasComponents.get(targetAlias);
  if (!targetComponent) return;

  const toolBounds = readBoundsForOverlap(oc, tool);
  const changed = new Set<string>();
  state.partSolidComponents.set(targetComponent, targetResult);
  changed.add(targetComponent);

  for (const [component, shape] of [...state.partSolidComponents]) {
    if (component === targetComponent) continue;
    if (!overlaps(oc, shape, toolBounds)) continue;
    state.partSolidComponents.set(component, applyCut(shape, tool, span));
    changed.add(component);
  }

  for (const [alias, component] of state.partSolidAliasComponents) {
    if (!changed.has(component)) continue;
    const shape = state.partSolidComponents.get(component);
    if (shape) registerAlias(state, alias, shape);
  }
  const first = state.partSolidComponents.values().next().value as
    | OC
    | undefined;
  if (first) state.bodyShapes.set(owner, first);
}

/**
 * Fuses deferred components into one topology when details or output require it.
 * Modifiers need coherent shared edges, but delaying this point keeps loops and
 * repeated cuts fast. Pairwise balanced fusion limits the growth of each boolean
 * step compared with repeatedly fusing into one ever-larger accumulator.
 */
export function flushDeferredPartSolid(
  state: GroupBuildState,
  span: SourceSpan,
  fuse: PartSolidFuse,
  registerAliases: PartSolidRegister,
): OC | null {
  const owner = state.partSolidOwner;
  if (!owner || state.partSolidComponents.size === 0) return state.partSolid;
  const shapes = [...state.partSolidComponents.values()];
  const fused = fuseBalanced(shapes, span, fuse);

  commitDeferredPartSolid(state, fused, registerAliases);
  return fused;
}

/** Commits a fused native batch through the established alias state contract. */
export function commitDeferredPartSolid(
  state: GroupBuildState,
  fused: OC,
  registerAliases: PartSolidRegister,
): void {
  const owner = state.partSolidOwner;
  if (!owner) return;
  state.partSolid = fused;
  state.bodyShapes.set(owner, fused);
  state.partSolidComponents.clear();
  state.partSolidComponents.set(owner, fused);
  for (const alias of state.partSolidAliases) {
    state.partSolidAliasComponents.set(alias, owner);
  }
  registerAliases(state, fused);
}

/**
 * Handles fuse balanced in the operations flow.
 */
function fuseBalanced(shapes: OC[], span: SourceSpan, fuse: PartSolidFuse): OC {
  if (shapes.length === 1) return shapes[0];
  let level = shapes;
  while (level.length > 1) {
    const next: OC[] = [];
    for (let i = 0; i < level.length; i += 2) {
      next.push(
        i + 1 < level.length
          ? fuse(level[i], level[i + 1], span, 'Part fuse failed')
          : level[i],
      );
    }
    level = next;
  }
  return level[0];
}

/**
 * Reads bounds for overlap from the supplied source.
 */
function readBoundsForOverlap(oc: OC, shape: OC): Bounds | null {
  try {
    return readBounds(oc, shape);
  } catch {
    return null;
  }
}

/**
 * Handles overlaps in the operations flow.
 */
function overlaps(oc: OC, shape: OC, toolBounds: Bounds | null): boolean {
  if (!toolBounds) return true;
  try {
    return boundsOverlap(readBounds(oc, shape), toolBounds);
  } catch {
    return true;
  }
}
