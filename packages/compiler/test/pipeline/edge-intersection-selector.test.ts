import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import type { IRFillet } from '@bushscad/ir';
import { previewFile } from '../../src/pipeline/previewFile.js';

const EXAMPLE = fileURLToPath(
  new URL(
    '../../../../examples/test_suite/15_edge_intersections.bscd',
    import.meta.url,
  ),
);

describe('edge intersection selector pipeline', () => {
  it('fillets only the solid edge generated by two aliased rectangle sides', async () => {
    const result = await previewFile({ filePath: EXAMPLE, occtTrace: true });
    expect(result.ok).toBe(true);
    if (!result.ok) return;

    const fillet = result.program.ops.find(
      (op): op is IRFillet => op.kind === 'fillet',
    );
    expect(fillet?.selection).toMatchObject({
      selectorKind: 'edge-intersection',
      edgeIntersection: {
        edgeLabels: ['crossed_body.h.top', 'crossed_body.v.right'],
      },
    });
    expect(
      result.validations.filter((validation) => !validation.passed),
    ).toEqual([]);
    expect(
      result.meshes.reduce(
        (triangleCount, mesh) => triangleCount + mesh.indices.length / 3,
        0,
      ),
    ).toBeGreaterThan(60);
    expect(
      result.interaction.entities.find(
        (entity) => entity.selectorKind === 'edge-intersection',
      ),
    ).toMatchObject({
      name: 'crossed_body.(h.top, v.right)',
      collectionValueCount: 1,
      collectionValues: [
        expect.stringContaining('crossed_body.h.top.edges — line (10, 10, 0)'),
      ],
    });
  }, 90_000);
});
